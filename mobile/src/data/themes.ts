export const themeOf = (key: string) => THEMES.find((t) => t.key === key);

/** Темы текста — в порядке словаря. */
export const findThemes = (text = '') => {
  const s = text.toLowerCase();
  return THEMES.filter((t) => t.words.test(s)).map((t) => t.key);
};

/** Договорённости и следующие шаги — «вехи» в майндмэпе. */
const DEAL = new RegExp([
  'договорил', 'договорённост', 'договоренност', 'следующ[а-яё]* шаг', 'пришлют', 'пришлёт', 'пришлет', 'отправ(ят|им|лю|ить им)',
  'созвон', 'повторн[а-яё]* встреч', 'образц', 'коммерческ[а-яё]* предложени', `${W}кп${W}`, `${W}пилот`, 'прислать',
  'до (конца )?\\d{0,2} ?(январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)', 'в (январе|феврале|декабре|ноябре)',
].join('|'));

export const findDeal = (text = '') => DEAL.test(text.toLowerCase());

/** Первая фраза заметки — для подписи в карте. */
export function snippet(text = '', max = 70) {
  const t = text.trim();
  const first = (t.match(/^[\s\S]*?[.!?](?=\s|$)/)?.[0] || t).trim();
  if (first.length <= max) return first.replace(/[.]$/, '');
  const cut = first.slice(0, max);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(' '), max - 12)).trimEnd().replace(/\s*[,:;—-]$/, '')}…`;
}
