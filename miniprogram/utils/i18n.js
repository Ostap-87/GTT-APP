const dicts = { zh, en };

function t(lang) {
  return lang === 'en' ? Object.assign({}, zh, en) : zh;
}

function fill(text, vars) {
  return String(text).replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] !== undefined ? vars[k] : ''));
}

// Поле сервера вида { zh, en } → строка на нужном языке.
function pick(obj, lang) {
  if (!obj) return '';
  return obj[lang] || obj.zh || '';
}

function applyTabBar(lang) {
  const tabs = t(lang).tabs;
  tabs.forEach((text, index) => wx.setTabBarItem({ index, text, fail() {} }));
}

module.exports = { t, fill, pick, applyTabBar, dicts };
